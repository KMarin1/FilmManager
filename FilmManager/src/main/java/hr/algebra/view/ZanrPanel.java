    private void init() {
        lsZanr.setModel(model);
        lsZanr.addListSelectionListener(e -> {
            if (!e.getValueIsAdjusting()) {
                    showZanr();
            }
        });
        loadRedatelji();

    }

    private void loadRedatelji() {
        try {
            model.clear();
            repository.getAllZanrovi().forEach(z -> {
                model.addElement((Zanr) z);
            });
        } catch (Exception ex) {
            MessageUtils.showErrorMessage("Greška", "Ne mogu dohvatiti glumce");
            Logger.getLogger(RedateljPanel.class.getName()).log(Level.SEVERE, null, ex);
        }
    }
