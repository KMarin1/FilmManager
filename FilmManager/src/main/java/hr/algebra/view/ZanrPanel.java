    Zanr selectedZanr = null;
    
    private void showZanr() {
        int selectedRow = lsZanr.getSelectedIndex();
        if (selectedRow < 0) {
            // ako nema selekcije, očisti formu i kosi selectedRedatelj
            clearForm();
            selectedZanr = null;
            return;
        }
        // tek kad je stvarno kliknuto na red:

        selectedZanr = model.getElementAt(selectedRow);
        tfIme.setText(selectedZanr.getNaziv());
        
    }
    
    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        if (!formValid()) {
            MessageUtils.showErrorMessage("Greška", "Unesite ime i prezime glumca.");
            return;
        }

        try {
            String ime = tfIme.getText().trim();
           

            Zanr zanr = new Zanr(ime);
            repository.insertZanr(zanr);
            MessageUtils.showInformationMessage("Uspjeh", "Zanr je dodan.");
            clearForm();

        } catch (DataAccessException ex) {
            Logger.getLogger(ZanrPanel.class.getName()).log(Level.SEVERE, null, ex);
            MessageUtils.showErrorMessage("Greška", "Ne mogu spremiti glumca.");
        }
    }//GEN-LAST:event_btnAddActionPerformed

    private void btnEditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditActionPerformed
        if (selectedZanr == null || !formValid()) {
            MessageUtils.showErrorMessage("Greška", "Odaberite glumca i unesite valjane podatke.");
            return;
        }
        try {
            selectedZanr.setNaziv(tfIme.getText().trim());
            repository.updateZanr(selectedZanr);
            lsZanr.repaint();
            clearForm();
        } catch (DataAccessException e) {
            Logger.getLogger(ZanrPanel.class.getName()).log(Level.SEVERE, null, e);
        }
    }//GEN-LAST:event_btnEditActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        if (selectedZanr == null) {
            MessageUtils.showErrorMessage("Greška", "Odaberite glumca za brisanje.");
            return;
        }
        try {
            repository.deleteZanr(selectedZanr.getId());
            model.removeElement(selectedZanr);
            clearForm();
        } catch (DataAccessException e) {
            Logger.getLogger(ZanrPanel.class.getName()).log(Level.SEVERE, null, e);
        }
    }//GEN-LAST:event_btnDeleteActionPerformed
        private boolean formValid() {
           return !tfIme.getText().trim().isEmpty();
       }

       private void clearForm() {
           tfIme.setText("");

       }

